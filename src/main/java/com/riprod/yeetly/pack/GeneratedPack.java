package com.riprod.yeetly.pack;

import com.google.gson.Gson;
import com.google.gson.GsonBuilder;
import com.google.gson.JsonElement;
import com.google.gson.JsonObject;
import com.hypixel.hytale.assetstore.AssetPack.PackSource;
import com.hypixel.hytale.common.plugin.PluginIdentifier;
import com.hypixel.hytale.common.plugin.PluginManifest;
import com.hypixel.hytale.common.semver.Semver;
import com.hypixel.hytale.logger.HytaleLogger;
import com.hypixel.hytale.server.core.asset.AssetModule;
import com.hypixel.hytale.server.core.plugin.PluginManager;

import javax.annotation.Nonnull;
import javax.annotation.Nullable;
import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.HashMap;
import java.util.function.Supplier;

public final class GeneratedPack {

    private static final String NAME_SUFFIX = "_Generated";
    private static final String MANIFEST_FILE = "manifest.json";
    private static final Gson GSON = new GsonBuilder().setPrettyPrinting().disableHtmlEscaping().create();

    private final PluginManifest owner;
    private final Path root;
    private final HytaleLogger logger;
    private final String packName;
    private boolean changed;

    public GeneratedPack(@Nonnull PluginManifest owner, @Nonnull HytaleLogger logger) {
        this.owner = owner;
        this.root = PluginManager.MODS_PATH.resolve(owner.getGroup() + "_" + owner.getName() + NAME_SUFFIX);
        this.logger = logger;
        this.packName = new PluginIdentifier(owner).toString() + NAME_SUFFIX;
    }

    public boolean writeJsonIfAbsent(@Nonnull String relativePath, @Nonnull Supplier<JsonElement> content) {
        return writeBytesIfAbsent(relativePath, () -> GSON.toJson(content.get()).getBytes(StandardCharsets.UTF_8));
    }

    public void register() {
        var manifest = new PluginManifest(
            owner.getGroup(), owner.getName() + NAME_SUFFIX,
            Semver.fromString("1.0.0"),
            "Throwable block assets generated by " + owner.getName(),
            new ArrayList<>(),
            "",
            null,
            owner.getServerVersion(),
            new HashMap<>(), new HashMap<>(), new HashMap<>(),
            new ArrayList<>(),
            false
        );
        writeJsonIfAbsent(MANIFEST_FILE, () -> manifestJson(manifest));

        var assetModule = AssetModule.get();
        if (assetModule.getAssetPack(packName) != null) {
            if (!changed) return;
            assetModule.unregisterPack(packName);
        }
        assetModule.registerPack(packName, root, manifest, PackSource.CLASSPATH);
        changed = false;
    }

    public boolean writeBytesIfAbsent(@Nonnull String relativePath, @Nonnull Supplier<byte[]> content) {
        var target = root.resolve(relativePath);
        if (Files.exists(target)) return false;

        var bytes = content.get();
        if (bytes == null) return false;

        try {
            Files.createDirectories(target.getParent());
            Files.write(target, bytes);
            changed = true;
            return true;
        } catch (IOException e) {
            logger.atWarning().withCause(e).log("Failed to write generated asset %s", target);
            return false;
        }
    }

    @Nonnull
    private static JsonElement manifestJson(@Nonnull PluginManifest manifest) {
        var json = new JsonObject();
        json.addProperty("Group", manifest.getGroup());
        json.addProperty("Name", manifest.getName());
        json.addProperty("Version", manifest.getVersion().toString());
        var serverVersion = serverVersion(manifest);
        if (serverVersion != null) json.addProperty("ServerVersion", serverVersion);
        json.addProperty("IncludesAssetPack", true);
        return json;
    }

    @Nullable
    private static String serverVersion(@Nonnull PluginManifest manifest) {
        var range = manifest.getServerVersion();
        return range == null ? null : range.toString();
    }
}
